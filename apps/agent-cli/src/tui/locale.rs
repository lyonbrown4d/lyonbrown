#[derive(Debug, Default, Clone, Copy, PartialEq, Eq)]
pub enum Locale {
  #[default]
  EnUs,
  ZhCn,
}

impl Locale {
  pub const fn id(self) -> &'static str {
    match self {
      Self::EnUs => "en-US",
      Self::ZhCn => "zh-CN",
    }
  }

  pub fn from_id(id: &str) -> Self {
    match id {
      "zh-CN" => Self::ZhCn,
      _ => Self::EnUs,
    }
  }

  pub(crate) const fn messages(self) -> Messages {
    match self {
      Self::EnUs => EN_US,
      Self::ZhCn => ZH_CN,
    }
  }
}

