use super::{large_text, snapshot_column};
use sea_orm_migration::prelude::*;
pub(super) async fn create(manager: &SchemaManager<'_>) -> Result<(), DbErr> {
  let backend = manager.get_database_backend();
  manager
    .create_table(
      Table::create()
        .table(Alias::new("sessions"))
        .col(ColumnDef::new(Alias::new("id")).string_len(256).not_null())
        .col(
          ColumnDef::new(Alias::new("owner_epoch"))
            .big_integer()
            .not_null(),
        )
        .col(large_text("record", backend))
        .primary_key(Index::create().col(Alias::new("id")))
        .to_owned(),
    )
    .await?;
  manager
    .create_table(
      Table::create()
        .table(Alias::new("runtime_sessions"))
        .col(
          ColumnDef::new(Alias::new("session_id"))
            .string_len(256)
            .not_null(),
        )
        .col(snapshot_column(backend))
        .primary_key(Index::create().col(Alias::new("session_id")))
        .to_owned(),
    )
    .await?;
  manager
    .create_table(
      Table::create()
        .table(Alias::new("runs"))
        .col(ColumnDef::new(Alias::new("id")).string_len(256).not_null())
        .col(
          ColumnDef::new(Alias::new("session_id"))
            .string_len(256)
            .not_null(),
        )
        .col(
          ColumnDef::new(Alias::new("idempotency_key"))
            .string_len(256)
            .not_null(),
        )
        .col(
          ColumnDef::new(Alias::new("status"))
            .string_len(256)
            .not_null(),
        )
        .col(
          ColumnDef::new(Alias::new("created_at_ms"))
            .big_integer()
            .not_null(),
        )
        .col(large_text("record", backend))
        .primary_key(Index::create().col(Alias::new("id")))
        .to_owned(),
    )
    .await?;
  manager
    .create_table(
      Table::create()
        .table(Alias::new("events"))
        .col(
          ColumnDef::new(Alias::new("run_id"))
            .string_len(256)
            .not_null(),
        )
        .col(
          ColumnDef::new(Alias::new("cursor"))
            .big_integer()
            .not_null(),
        )
        .col(large_text("record", backend))
        .primary_key(
          Index::create()
            .col(Alias::new("run_id"))
            .col(Alias::new("cursor")),
        )
        .to_owned(),
    )
    .await?;
  manager
    .create_table(
      Table::create()
        .table(Alias::new("outbox"))
        .col(
          ColumnDef::new(Alias::new("run_id"))
            .string_len(256)
            .not_null(),
        )
        .col(
          ColumnDef::new(Alias::new("cursor"))
            .big_integer()
            .not_null(),
        )
        .col(ColumnDef::new(Alias::new("delivered")).integer().not_null())
        .primary_key(
          Index::create()
            .col(Alias::new("run_id"))
            .col(Alias::new("cursor")),
        )
        .to_owned(),
    )
    .await?;
  manager
    .create_table(
      Table::create()
        .table(Alias::new("write_lock"))
        .col(ColumnDef::new(Alias::new("id")).integer().not_null())
        .col(
          ColumnDef::new(Alias::new("revision"))
            .big_integer()
            .not_null(),
        )
        .primary_key(Index::create().col(Alias::new("id")))
        .to_owned(),
    )
    .await?;
  Ok(())
}
